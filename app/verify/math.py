"""Compute-don't-trust verification - the heart of PrepRight.

THE INVERSION (why this file exists):
LLMs hallucinate arithmetic. A tutoring app that serves a wrong answer key
to a 13-year-old is dead on arrival. So we flip the pipeline:

    TRADITIONAL:  LLM writes question AND answer  -> pray it's right
    PREPRIGHT:    LLM writes question + machine SPEC
                  sympy solves the spec           -> answer key is OURS

Three verification layers, all deterministic:
1. solve_spec()       - sympy computes the ground-truth answer from the spec
2. coherence_check()  - the numbers in the spec must appear in the question
                        text (catches the model phrasing a DIFFERENT
                        question than it spec'd - classic structured-output drift)
3. distractors()      - wrong MCQ options are generated by code from the
                        correct answer (misconception-flavored), never by the LLM

Spec types are a closed set: the LLM may only pick from these. An unknown
type fails verification -> the question is dropped. Extend by adding a
solver here; the model learns new types via the tool prompt (tools.py).
"""

from dataclasses import dataclass

from sympy import Rational, Symbol, gcd, lcm, solve, sympify

# ---------------------------------------------------------------- result type

@dataclass
class Verified:
    """Outcome of verifying ONE drafted question."""
    ok: bool
    reason: str = ""          # why it failed (telemetry + debugging)
    answer: str = ""          # canonical correct answer, human-formatted
    options: list[str] = None # MCQ options incl. the correct one (unshuffled; correct = options[0] before shuffle)
    skill: str = ""


# ---------------------------------------------------------------- formatting

def _fmt(value) -> str:
    """Canonical human format: 3 not 3.0; 7/2 not 3.5 for rationals."""
    if isinstance(value, Rational) and value.q == 1:
        return str(value.p)
    if isinstance(value, Rational):
        return f"{value.p}/{value.q}"
    if isinstance(value, (int,)):
        return str(value)
    return str(value)


def _roots_pair(coeffs: dict) -> tuple:
    """Solve a*x^2 + b*x + c = 0 -> sorted numeric roots."""
    x = Symbol("x")
    poly = coeffs["a"] * x**2 + coeffs["b"] * x + coeffs["c"]
    roots = solve(poly, x)
    nums = []
    for r in roots:
        rn = Rational(r)
        nums.append(rn)
    return tuple(sorted(nums))


# ---------------------------------------------------------------- layer 1: solve

def solve_spec(spec: dict) -> tuple[str, object]:
    """Compute the ground-truth answer from a machine spec.

    Returns (answer_text, answer_value). Raises on unknown/invalid specs -
    which is exactly what we want: an unsolvable spec = unverified question.
    """
    t = spec.get("type")

    if t == "arithmetic":
        # e.g. {"expr": "12 + 7 * 3"} - integers only in v1 specs
        v = sympify(spec["expr"])
        return _fmt(v), v

    if t == "linear_eq":
        # a*x + b = c  ->  x = (c - b) / a
        v = Rational(spec["c"] - spec["b"], spec["a"])
        return _fmt(v), v

    if t == "quadratic_roots":
        # a*x^2 + b*x + c = 0 -> both roots, formatted as a pair
        r1, r2 = _roots_pair(spec)
        text = f"x = {_fmt(r1)} or x = {_fmt(r2)}"
        return text, (r1, r2)

    if t == "evaluate":
        # evaluate expr at a value, e.g. {"expr": "x**2 + 5*x + 6", "x": 2}
        x = Symbol("x")
        v = sympify(spec["expr"]).subs(x, spec["val"])
        v = Rational(v)
        return _fmt(v), v

    if t == "percentage":
        # {"part": 45, "whole": 60} -> 75 (%)
        v = Rational(spec["part"] * 100, spec["whole"])
        return _fmt(v), v

    if t == "gcd_lcm":
        # {"m": 12, "n": 18, "op": "hcf" | "lcm"}
        m, n = spec["m"], spec["n"]
        v = int(gcd(m, n)) if spec["op"] == "hcf" else int(lcm(m, n))
        return str(v), v

    raise ValueError(f"unknown spec type: {t!r}")


# ---------------------------------------------------------------- layer 2: coherence

def coherence_check(question_text: str, spec: dict) -> bool:
    """Every meaningful number in the spec must appear in the question text.

    Why: structured-output drift. The model sometimes phrases a question
    about DIFFERENT numbers than the spec it emitted (it 'changed its mind'
    mid-generation). Then our computed answer would be right for the spec
    but wrong for the question shown to the student. This check kills that
    class of bug entirely.

    Formatting tolerance (learned from test failures):
    - compare against a SPACE-STRIPPED text: '- 5' must match spec b=-5
    - skip coefficients 0 and 1: 'x^2 - 5x + 6' never shows the 1
    - for gcd_lcm, the op word (HCF/LCM) must appear in the text too:
      a model phrasing 'HCF' with op=lcm would compute the WRONG answer
      for the question shown - numbers alone wouldn't catch that.
    """
    compact = question_text.replace(" ", "")
    for k, v in spec.items():
        if k in ("type", "op", "expr"):
            continue
        if isinstance(v, (int, float)):
            if v in (0, 1):  # implicit/identity coefficients
                continue
            if str(v) not in compact:
                return False

    if "op" in spec and spec["type"] == "gcd_lcm":
        synonyms = {"hcf": ["hcf", "gcd", "highest common factor"],
                    "lcm": ["lcm", "least common multiple", "lowest common multiple"]}
        words = synonyms.get(spec["op"], [])
        if words and not any(w in question_text.lower() for w in words):
            return False
    return True


# ---------------------------------------------------------------- layer 3: distractors

def make_options(answer_text: str, answer_value, spec: dict) -> list[str]:
    """4 MCQ options: [correct_answer] + 3 code-generated distractors.

    CONTRACT (tools.py relies on it): options[0] is ALWAYS the correct
    answer before shuffling. Distractors mirror REAL misconceptions per
    question type (sign flips, gcd-vs-lcm confusion, off-by-one), because
    good wrong options teach.
    """
    t = spec.get("type")

    def uniq(vals):
        seen, kept = set(), []
        for v in vals:
            if v not in seen:
                seen.add(v)
                kept.append(v)
        return kept

    if t == "quadratic_roots":
        r1, r2 = answer_value
        cands = [
            f"x = {_fmt(-r1)} or x = {_fmt(-r2)}",          # both signs flipped
            f"x = {_fmt(r1)} or x = {_fmt(-r2)}",           # one sign flipped
            f"x = {_fmt(r1 + r2)} or x = {_fmt(r1 * r2)}",  # sum/product confusion
        ]
    elif t == "gcd_lcm":
        m, n = spec["m"], spec["n"]
        other = int(lcm(m, n)) if spec["op"] == "hcf" else int(gcd(m, n))
        cands = [str(other), str(m * n), str(m + n)]        # classic confusions
    else:
        # numeric answers: off-by-one, doubled, sign flip, big miss
        v = answer_value
        cands = [_fmt(c) for c in (v + 1, v - 1, -v, 2 * v, v + 10)]

    distractors = uniq([c for c in cands if c != answer_text])[:3]
    while len(distractors) < 3:  # degenerate case (e.g. answer 0 kills -v and 2*v)
        cand = _fmt(answer_value + len(distractors) + 2)
        if cand not in distractors and cand != answer_text:
            distractors.append(cand)

    return [answer_text, *distractors]


# ---------------------------------------------------------------- the gate

def verify_question(question_text: str, spec: dict, skill: str = "") -> Verified:
    """Run a drafted question through all three layers. ok=False -> dropped.

    Order matters: SOLVE first (unknown/invalid specs get the precise
    'unsolvable' reason), then coherence (solvable but mis-phrased).
    """
    try:
        answer, value = solve_spec(spec)                 # layer 1: compute
        if not coherence_check(question_text, spec):     # layer 2: drift check
            return Verified(False, reason="spec numbers not in question text", skill=skill)
        options = make_options(answer, value, spec)      # layer 3: distractors
        return Verified(True, answer=answer, options=options, skill=skill)
    except Exception as exc:  # unknown type, bad params, sympy error
        return Verified(False, reason=f"unsolvable spec: {exc}", skill=skill)
